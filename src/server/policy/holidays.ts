/** 공휴일 목록이 있는 마지막 해. 이 해가 끝나기 전에 다음 해 목록을 넣는다 */
export const PUBLIC_HOLIDAYS_LAST_YEAR = 2027;

const HOLIDAY_SET: ReadonlySet<string> = new Set(PUBLIC_HOLIDAYS);
const HOUR_MS = 60 * 60 * 1000;
const DAY_MS = 24 * HOUR_MS;

/** 그 시각의 한국 날짜가 영업일인지(토·일·공휴일이 아닌 날) */
export function isBusinessDay(date: Date): boolean {
  const { weekday } = utcToKst(date);
  return weekday !== 0 && weekday !== 6 && !HOLIDAY_SET.has(kstDateKey(date));
}

/**
 * base부터 영업일의 시간만 hours시간 센 때. 토·일·공휴일은 하루 통째로 세지 않는다.
 * 예: 일요일 15:00 + 48 → 수요일 00:00, 금요일 15:00 + 48 → 다음 주 화요일 15:00
 */
export function addBusinessHours(base: Date, hours: number): Date {
  if (!Number.isFinite(hours) || hours < 0) {
    throw new RangeError(`영업일 시간이 올바르지 않아요: ${hours}`);
  }
  let remaining = hours * HOUR_MS;
  let cursor = base;
  // 공휴일이 길게 이어져도 1년 안에서 끝난다
  for (let day = 0; day < 366; day += 1) {
    const { year, month, day: date } = utcToKst(cursor);
    const nextDay = new Date(
      kstToUtc({ year, month, day: date, hour: 0, minute: 0 }).getTime() + DAY_MS,
    );
    if (isBusinessDay(cursor)) {
      const available = nextDay.getTime() - cursor.getTime();
      if (remaining <= available) return new Date(cursor.getTime() + remaining);
      remaining -= available;
    }
    cursor = nextDay;
  }
  throw new RangeError('영업일 시간을 1년 안에 다 세지 못했어요');
}
